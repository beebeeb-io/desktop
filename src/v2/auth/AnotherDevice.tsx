// DW-A07 to A10: sign in with another device, the requesting side. The QR (drawn in Rust; its link carries no code),
// the code in mono, the countdown, then approved, denied or expired.
import { Icon } from '@beebeeb/shared/design'
import { countdown, type DeviceStatus } from './model'
import { AuthWindow, Heading, Note, PrimaryButton, Ring, SecondaryButton, StepLockup, TextLink, Tile } from './parts'

export interface AnotherDeviceViewProps {
  status: DeviceStatus | 'starting'
  code: string | null
  secondsLeft: number
  /** This PC's name as the approver will see it. */
  deviceName: string | null
  /** The approving device's name, when the server says it (A08, A09). */
  approverName?: string | null
  qrSvg: string | null
  onCopyCode: () => void
  onOpenDrive: () => void
  onAskAgain: () => void
  onUseEmail: () => void
}

const LIFETIME = 300

export function AnotherDeviceView(p: AnotherDeviceViewProps) {
  if (p.status === 'approved' || p.status === 'signed_in') return <Approved {...p} />
  if (p.status === 'keys_did_not_arrive') {
    return (
      <AuthWindow>
        <Tile icon="info" tone="red" />
        <Heading>Approved, but the keys did not arrive</Heading>
        <Note tone="red">Nothing was signed in. Ask again.</Note>
        <Actions primary="Ask again" onPrimary={p.onAskAgain} onUseEmail={p.onUseEmail} />
      </AuthWindow>
    )
  }
  if (p.status === 'denied') {
    return (
      <AuthWindow>
        <Tile icon="x" tone="neutral" />
        <Heading sub={`${p.approverName ?? 'The other device'} said no.`}>Denied</Heading>
        <p className="mb-5 text-[13px] text-ink-2">Nothing was signed in and no keys were shared.</p>
        <Actions primary="Ask again" onPrimary={p.onAskAgain} onUseEmail={p.onUseEmail} />
      </AuthWindow>
    )
  }
  const expired = p.status === 'expired' || p.status === 'failed'
  const reconnecting = p.status === 'reconnecting'
  return (
    <AuthWindow>
      <StepLockup />
      <div className="mt-4" />
      <Heading sub="On a phone or computer where you’re signed in to Beebeeb, open Account › Approve a sign-in and type this code.">
        Sign in with another device
      </Heading>
      {expired && <Note tone="red" title="This code expired">Nothing was signed in.</Note>}
      <div className={`flex items-center gap-5 ${expired ? 'opacity-40' : ''}`} data-request>
        <div
          className="h-[132px] w-[132px] flex-none rounded-md border border-line bg-white p-1.5 text-black [&>svg]:h-full [&>svg]:w-full"
          data-qr
          aria-label="QR code that opens this request on the other device"
          role="img"
          // The SVG is generated by Rust from the approval page's link (no code in it); never from page input.
          dangerouslySetInnerHTML={p.qrSvg ? { __html: p.qrSvg } : undefined}
        />
        <div className="min-w-0">
          <div className="text-[11px] uppercase tracking-wide text-ink-3">Code</div>
          <button type="button" onClick={p.onCopyCode} title="Copy the code (Ctrl+C)" className="mt-0.5 block font-mono text-[26px] font-semibold tracking-[0.06em] text-ink" data-code>
            {p.code ?? '····-····'}
          </button>
          <div className="mt-2 flex items-center gap-3">
            <Ring fraction={p.secondsLeft / LIFETIME} label={expired ? 'Expired' : `Expires in ${countdown(p.secondsLeft)}`} dim={expired} />
          </div>
          {!expired && (
            <span data-pill className="mt-2 inline-flex items-center gap-1.5 rounded-full border border-line bg-paper-2 px-2.5 py-0.5 text-[11px] text-ink-2">
              <span className="h-1.5 w-1.5 rounded-full bg-ink-3" />{reconnecting ? 'Reconnecting…' : p.status === 'starting' ? 'Getting a code…' : 'Waiting for approval'}
            </span>
          )}
        </div>
      </div>
      <p className="mt-4 text-[12px] text-ink-3">
        This device asks as <span className="font-mono text-ink-2">{p.deviceName ?? 'this PC'}</span>
      </p>
      <div className="mt-5 flex flex-col gap-2.5">
        {expired && <PrimaryButton onClick={p.onAskAgain}>Get a new code</PrimaryButton>}
        <div className="text-center"><TextLink onClick={p.onUseEmail}>Use email and password instead</TextLink></div>
      </div>
    </AuthWindow>
  )
}

function Approved(p: AnotherDeviceViewProps) {
  return (
    <AuthWindow>
      <Tile icon="check" tone="green" />
      <Heading sub={`${p.approverName ?? 'Your other device'} approved this PC. Nothing was typed here.`}>Approved</Heading>
      <Note tone="amber">Your keys arrived encrypted for this device only. Beebeeb can’t read them.</Note>
      <PrimaryButton onClick={p.onOpenDrive} disabled={p.status !== 'signed_in'}>
        {p.status === 'signed_in' ? 'Open Drive' : 'Storing your keys…'}
      </PrimaryButton>
    </AuthWindow>
  )
}

function Actions({ primary, onPrimary, onUseEmail }: { primary: string; onPrimary: () => void; onUseEmail: () => void }) {
  return (
    <div className="flex flex-col gap-2.5">
      <PrimaryButton onClick={onPrimary}><Icon name="key" size={15} />{primary}</PrimaryButton>
      <SecondaryButton onClick={onUseEmail}>Use email and password instead</SecondaryButton>
    </div>
  )
}
