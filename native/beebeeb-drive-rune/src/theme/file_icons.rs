fn lookup(table: &[(&str, IconId, Tint)], key: &str) -> Option<FileIcon> {
    table
        .iter()
        .find(|(k, _, _)| *k == key)
        .map(|&(_, id, tint)| FileIcon { id, tint })
}

pub fn icon_for(name: &str, is_dir: bool, mime: Option<&str>) -> FileIcon {
    let lower = name.to_lowercase();
    let n = lower.trim();
    if is_dir {
        return lookup(FOLDER_NAMES, n).unwrap_or(FileIcon {
            id: IconId::Folder,
            tint: Tint::Folder,
        });
    }
    if let Some(fi) = lookup(FILE_NAMES, n) {
        return fi;
    }
    for (i, _) in n.match_indices('.') {
        if i > 0 {
            if let Some(fi) = lookup(EXTENSIONS, &n[i + 1..]) {
                return fi;
            }
        }
    }
    if let Some(m) = mime {
        let (id, tint) = if m.starts_with("image/") {
            (IconId::Image, Tint::Image)
        } else if m.starts_with("video/") {
            (IconId::Video, Tint::Video)
        } else if m.starts_with("audio/") {
            (IconId::Audio, Tint::Audio)
        } else if m == "application/pdf" {
            (IconId::Pdf, Tint::Pdf)
        } else if m.starts_with("text/") {
            (IconId::Text, Tint::Word)
        } else {
            (IconId::File, Tint::Default)
        };
        return FileIcon { id, tint };
    }
    FileIcon {
        id: IconId::File,
        tint: Tint::Default,
    }
}

pub fn icon_for_item(item: &crate::source::DriveItem) -> FileIcon {
    if item.is_folder && item.is_protected {
        return FileIcon {
            id: IconId::FolderBackups,
            tint: Tint::Folder,
        };
    }
    icon_for(&item.name, item.is_folder, item.mime.as_deref())
}

