/// The file the installer puts beside the app exe (`packaging/windows/installer.nsi`; generated by
/// `packaging/licences/generate.sh`): every third-party licence, our own AGPL-3.0 text and the source locations.
pub const LICENCES_FILE: &str = "THIRD-PARTY-LICENSES.md";
/// Under the Open source list: the source-availability line (AGPL-3.0 section 13: the source is offered to every user).
pub const SOURCE_LINE: &str =
    "Beebeeb is free software under the AGPL-3.0-or-later. Source code: github.com/beebeeb-io/desktop";
/// Shown when this build has no installed notice beside it (a development build, or a damaged install).
pub const LICENCES_MISSING: &str = "The licence file is not installed with this build";

/// Where the licence file sits for the program at `exe`: in the same folder.
pub fn licences_beside(exe: &std::path::Path) -> std::path::PathBuf {
    exe.with_file_name(LICENCES_FILE)
}

/// Opens `file` through `open_file` (the one way a file opens in the app: the in-app viewer shows the notice as
/// formatted Markdown) when it is there; `Err` is the words for the toast. This page only names the file.
fn open_licences_at(s: &mut State, file: Option<std::path::PathBuf>) -> Result<(), &'static str> {
    use crate::frames::open_file::{open_file, Opened, Target};
    let file = file.filter(|f| f.is_file()).ok_or(LICENCES_MISSING)?;
    match open_file(s, Target::Path(file)) {
        Opened::Failed(_) => Err("Could not open that file"),
        _ => Ok(()),
    }
}

/// Settings' `Open-source licences` and the Office dialog's `Third-party licences`: the installed notice beside the
/// exe, through `open_file`. `Err`: the words the toast of the pane shows (and the shell logs).
pub fn open_licences(s: &mut State) -> Result<(), &'static str> {
    let file = std::env::current_exe().ok().map(|exe| licences_beside(&exe));
    open_licences_at(s, file)
}

/// Where the Release channel menu drops, from its row's top-left corner (the board's place,
/// DW-0789: the menu at 702, 345 over the row at 254, 344).
const CHANNEL_MENU_AT: (f32, f32) = (448.0, 1.0);

pub fn pane(ui: &SettingsUi, t: &Theme) -> (El, Option<El>) {
    let a = ui.source.about();
    let menu_open = ui.menu.is_some_and(|m| m.kind == MenuKind::Channel);

    let copy_text = format!("{} {} ({})\nEncryption core {}", a.product, a.version, a.build, a.core);
    let product = cards::card(0, t)
        .child(kit::mark("card-0-mark", 44.0))
        .child(
            col()
                .key("card-0-words")
                .grow(1.0)
                .min_w(0.0)
                .child(cards::head(0, &a.product, t))
                .child(cards::sub(0, &a.tagline, t)),
        )
        .child(
            controls::button(0, "Copy", Some(&ic::COPY), Emphasis::Plain, t)
                .on_press(move |s: &mut State| s.settings.ask(Intent::Copy(copy_text.clone()))),
        );

    let versions = lists::list(
        0,
        None,
        vec![
            lists::item(
                0,
                0,
                &Item::new(None, "Version").trailing(Trailing::Mono(format!("{} ({})", a.version, a.build))),
                t,
            ),
            lists::item(
                0,
                1,
                &Item::new(None, "Encryption core")
                    .trailing(Trailing::Mono(a.core.clone()))
                    .ruled(),
                t,
            ),
        ],
        None,
        t,
    );

    // While a check runs the row says so and the button waits (DW-0751, Rules); so does the update's press, whose
    // step the row says.
    let live = ui.source.updates_available();
    let checking = matches!(a.check, UpdateCheck::Checking | UpdateCheck::Working(_));
    let mut check_now = controls::button(1, "Check now", None, Emphasis::Plain, t);
    check_now = if !live || checking {
        check_now.disabled(true).focusable(false)
    } else {
        check_now.on_press(|s: &mut State| s.settings.check_for_updates())
    };
    let mut update_rows = vec![
        lists::item_with(
            1,
            0,
            &Item::new(Some(&ic::DOWNLOAD_TRAY), "Check for updates").sub(if live {
                a.check.says()
            } else {
                NO_UPDATER_SUB
            }),
            vec![check_now],
            t,
        ),
        super::menu_keys(
            {
                let row = lists::item(
                    1,
                    1,
                    &Item::new(Some(&ic::SYNC), "Release channel")
                        .sub(if live { a.channel.says() } else { NO_UPDATER_SUB })
                        .trailing(Trailing::Pop {
                            choice: a.channel.label().into(),
                            open: menu_open,
                            menu_at: CHANNEL_MENU_AT,
                        })
                        .role(Role::PopUp),
                    t,
                );
                // No updater runs here: the row is shown and does nothing (no menu to open).
                if live {
                    row.on_press(|s: &mut State| s.settings.toggle_menu(MenuKind::Channel))
                } else {
                    row.disabled(true).focusable(false)
                }
            },
            MenuKind::Channel,
        ),
    ];
    // The release notes open only where the source has notes to show (in the app: a newer version on offer). Where
    // they do not, no row points to them: a link that opens nothing is a dead control (design note in FRAMES.md).
    let notes_open = ui.source.opens("DW-0789b");
    // The chosen channel is behind this PC's version: said, with the way to the notes where they open; nothing
    // is installed and nothing is offered (DW-0789, Rules).
    if let Some(older) = &a.older {
        let row = if notes_open {
            Item::new(Some(&ic::INFO), older.title()).sub(older.says()).opens()
        } else {
            Item::new(Some(&ic::INFO), older.title()).sub(older.runs_from())
        };
        let row = lists::item(1, update_rows.len(), &row.ruled(), t);
        update_rows.push(if notes_open {
            row.on_press(|s: &mut State| super::go(s, "DW-0789b"))
        } else {
            row
        });
    }
    if notes_open {
        update_rows.push(
            lists::item(
                1,
                update_rows.len(),
                &Item::new(Some(&ic::DOCUMENT), "Release notes")
                    .sub("What changed in each version")
                    .opens(),
                t,
            )
            .on_press(|s: &mut State| super::go(s, "DW-0789b")),
        );
    }
    let updates = lists::list(
        1,
        Some("Updates"),
        update_rows,
        Some(if live { UPDATES_LINE } else { NO_UPDATER_LINE }),
        t,
    );

    let web = |l: usize, i: usize, title: &str, page: &'static str, ruled: bool| {
        let mut it = Item::new(None, title).trailing(Trailing::External).role(Role::Link);
        if ruled {
            it = it.ruled();
        }
        lists::item(l, i, &it, t).on_press(move |s: &mut State| s.settings.ask(Intent::Web(page)))
    };
    let open_source = lists::roving_list(
        2,
        Some("Open source"),
        vec![
            web(2, 0, "Encryption core on GitHub", "encryption-core-on-github", false),
            lists::item(2, 1, &Item::new(None, "Open-source licences").opens().ruled(), t)
                .on_press(|s: &mut State| s.settings.ask(Intent::Open("open-source-licences"))),
            web(2, 2, "Source code for this version", "desktop-source", true),
        ],
        Some(SOURCE_LINE),
        t,
    );
    let more = lists::roving_list(
        3,
        Some("More"),
        vec![
            // "About audits" is not drawn: the site has no audits page to send to (`shell::web_pages`). The first
            // row of its list: no rule above it (the board, recaptured without audits).
            web(3, 0, "beebeeb.io", "beebeeb.io", false),
        ],
        Some(&a.company),
        t,
    );

    let mut children = vec![
        shell::crumb("General", t, |s: &mut State| super::go(s, "DW-0701")),
        shell::heading("About Beebeeb", None, t),
        product,
        versions,
    ];
    // Always drawn; in a build with no updater it is disabled and says why.
    children.push(updates);
    children.extend([open_source, more]);

    let overlay = match ui.dialog {
        Some(Dialog::ReleaseNotes) => Some(release_notes(ui, t)),
        _ => super::menu_overlay(ui, MenuKind::Channel, t),
    };
    (shell::pane(children, t), overlay)
}

/// What a version changes, before downloading it (DW-0789b).
fn release_notes(ui: &SettingsUi, t: &Theme) -> El {
    let n = ui.source.about().notes;
    let title = format!("Beebeeb {}", n.version);
    // The updater's offer carries no release date: the sub says the channel alone then, never "released " and nothing.
    let sub = if n.released.is_empty() {
        format!("{} channel", n.channel.label())
    } else {
        format!("{} channel · released {}", n.channel.label(), n.released)
    };
    let notes = if n.lines.is_empty() {
        dialogs::bullets(&["No release notes were provided for this version.".to_string()], t)
    } else {
        dialogs::bullets(&n.lines, t)
    };
    // One press: Restart to update downloads, checks and installs (owner ruling 2026-11-15); a newer version's notes
    // only (an older one is never offered: the source puts no older version's notes here). While the press has words
    // (its step, what failed, why it waits), the caption says them, as General's banner does.
    let caption = match ui.source.general().update {
        Update::Available { says: Some(says), .. } => says,
        _ => UPDATE_CAPTION.to_string(),
    };
    let body = vec![notes, dialogs::caption(0, &caption, t)];
    let press = n.press;
    let mut action = dialogs::button(2, press.label(), Weight::Primary, t);
    action = if press == Press::Wait {
        action.disabled(true).focusable(false)
    } else {
        action.default_button().on_press(move |s: &mut State| {
            s.settings.dialog = None;
            s.settings.press_update(press);
        })
    };
    let foot = vec![
        action,
        dialogs::button(3, "Close", Weight::Quiet, t).on_press(|s: &mut State| s.settings.dialog = None),
    ];
    dialogs::dialog(&title, 480.0, &title, Some(&sub), body, foot, t)
        .modal(false, |s: &mut State| s.settings.dialog = None)
}

#[cfg(test)]
mod about_tests {
    use super::*;
    use crate::frames::files::source::{Call, FilesFixture};
    use std::path::{Path, PathBuf};

    fn a_file(name: &str) -> PathBuf {
        let dir = std::env::temp_dir().join(format!("bb-about-{}-{name}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let f = dir.join(name);
        std::fs::write(&f, "# Notice\n\n- one\n").unwrap();
        f
    }

    fn spied() -> (State, std::sync::Arc<std::sync::Mutex<Vec<Call>>>) {
        let mut s = crate::init();
        let fixture = FilesFixture::default();
        let calls = fixture.calls.clone();
        s.actions.source = Box::new(fixture);
        (s, calls)
    }

    #[test]
    fn about_licence_file_sits_beside_the_exe_by_the_installers_name() {
        let exe = Path::new("C:/Users/x/AppData/Local/Beebeeb/beebeeb-desktop.exe");
        assert_eq!(
            licences_beside(exe),
            Path::new("C:/Users/x/AppData/Local/Beebeeb/THIRD-PARTY-LICENSES.md")
        );
        let nsi = include_str!("../../../../../packaging/windows/installer.nsi");
        assert!(
            nsi.contains(&format!("$INSTDIR\\{LICENCES_FILE}")),
            "the installer installs it under this name"
        );
        assert!(
            nsi.contains(&format!("Delete \"$INSTDIR\\{LICENCES_FILE}\"")),
            "and the uninstaller removes it"
        );
        assert!(nsi.contains("licences.lnk"), "and gives it a Start Menu entry");
    }

    #[test]
    fn about_passes_the_licence_file_to_open_file_and_says_when_it_is_not_there() {
        // A Markdown notice has an in-app preview: it opens in the viewer, the system is not asked.
        let (mut s, calls) = spied();
        let f = a_file(LICENCES_FILE);
        assert_eq!(open_licences_at(&mut s, Some(f.clone())), Ok(()));
        assert!(calls.lock().unwrap().is_empty(), "nothing went outside the app");
        assert!(s.viewer.ui.is_some(), "the notice is in the viewer");
        assert!(matches!(
            s.viewer.ui.as_ref().unwrap().file.body,
            crate::frames::viewers::source::Body::Markdown(_)
        ));
        let gone = std::env::temp_dir().join("bb-about-none").join(LICENCES_FILE);
        assert_eq!(open_licences_at(&mut s, Some(gone)), Err(LICENCES_MISSING));
        assert_eq!(open_licences_at(&mut s, None), Err(LICENCES_MISSING));
        // A kind with no preview goes outside, by the order of open_file.
        let (mut s, calls) = spied();
        let other = a_file("notice.bin");
        assert_eq!(open_licences_at(&mut s, Some(other.clone())), Ok(()));
        assert_eq!(*calls.lock().unwrap(), [Call::OpenPathDefault(other)]);
    }

    #[test]
    fn about_source_line_names_the_licence_and_the_repository() {
        assert!(SOURCE_LINE.contains("AGPL-3.0-or-later"));
        assert!(SOURCE_LINE.contains("github.com/beebeeb-io/desktop"));
    }

    #[test]
    fn about_licences_row_is_routed_to_the_opener() {
        let router = include_str!("../../shell/settings_open.rs");
        assert!(
            router.contains("\"open-source-licences\" => {"),
            "the shell routes the row to open_licences"
        );
        assert!(router.contains("about::open_licences(s)"));
    }

    #[test]
    fn about_licence_notice_stays_open_when_settings_was_in_front() {
        // the Windows test machine, 2026-11-20: About lives inside Settings. The route machine refuses OpenItem while Settings is
        // open, so the viewer's file was never the route's item and `sync` dropped it: the row did nothing.
        let (mut s, _calls) = spied();
        crate::shell::host::dispatch(
            &mut s,
            crate::shell::app::Event::OpenSettings(crate::shell::app::SettingsPane::General),
        );
        let f = a_file(LICENCES_FILE);
        assert_eq!(open_licences_at(&mut s, Some(f.clone())), Ok(()));
        crate::frames::viewers::sync(&mut s);
        assert!(
            s.viewer.ui.is_some(),
            "the notice is still open after the route settled"
        );
        assert!(
            matches!(s.shell.app.screen(), crate::shell::app::Screen::Drive(_)),
            "Settings made way for the viewer"
        );
        assert_eq!(
            crate::frames::viewers::route_item(&s),
            Some(f.to_string_lossy().into_owned())
        );
    }
}
