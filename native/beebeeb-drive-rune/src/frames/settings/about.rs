const UPDATES_LINE: &str = "Beebeeb checks for updates at launch and every 4 hours.";
/// A test or local build (no release version or build time): the updates section says so, disabled.
pub const NO_UPDATER_LINE: &str = "This test build doesn't update itself. Release builds check for updates here.";
const NO_UPDATER_SUB: &str = "Unavailable in this test build";

