//! Creating an account, for a host without a UI toolkit (the native sign-up screens, DW-A31 to DW-A44): the email
//! code, the password and its breach check, the twelve-word phrase, the OPAQUE registration, and the session of
//! the account that was just made.
//!
//! Every rule is core's `signup_flow::SignupFlow` (the same one the web and the phone run): this module sends the
//! requests it hands out, reads the answers back into it, and maps core's codes to the kinds a screen draws. It
//! adds no cryptography and no parameter. The server's numbers (password minimum, code length, resend wait, how
//! many words are asked back) come from its onboarding document and are never hard-coded here.
//!
//! Sign-up has no session, so the state of one attempt lives in a [`SignupAttempt`] the host owns and passes to
//! every call. [`SignupAttempt::cancel`] ends the attempt: the flow is wiped (password, phrase, ticket, key), and
//! every call that was on its way sees it and ends with `Left` instead of writing anything.
//!
//! Every method BLOCKS on the handle's runtime: call it from a worker thread, never from the UI thread. The
//! getters on [`SignupAttempt`] never wait for the network; they read snapshots, and the two that touch the flow
//! (`with_phrase`) give up at once when the worker holds it.
//!
//! The secrets: the password arrives as a `Zeroizing` buffer and goes into core; the phrase is generated by core,
//! held by core, and lent for one draw ([`SignupAttempt::with_phrase`]); the master key leaves core once, into the
//! credential store and the session. Must not: log or format a password, a code, a word, a ticket, a token, a
//! key, an email or a server's body. Only kinds leave this module.

use std::sync::Mutex;
use std::sync::atomic::{AtomicU64, Ordering};

use beebeeb_core::onboarding::PasswordHint;
use beebeeb_core::signup_flow::{SignupError, SignupFlow, SignupPolicy};
use zeroize::Zeroizing;

use super::{CredentialStores, Engine};
use crate::auth_transport;
use crate::keychain::SecretBytes;
use crate::session::Session;
use crate::signin::key_owner;
use crate::signin::store;

/// How many words are asked back. The screens draw three boxes; a server that asks for more is refused honestly.
pub const CONFIRM_WORDS: usize = 3;

/// The most of a breach answer that is read (a range answer is a few hundred lines of a few dozen bytes).
const BREACH_BODY_CAP: usize = 4 * 1024 * 1024;

/// Why no code was sent.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum SignupSendProblem {
    RateLimited {
        seconds: u32,
    },
    Offline,
    /// The server does not take sign-ups from this app (yet): the page it names is the way. The address is read
    /// with [`SignupAttempt::web_address`].
    WebOnly,
    Other,
    /// The attempt was ended while this was on its way.
    Left,
}

/// What a sent code allows (the server's numbers).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct SignupCodeSent {
    pub digits: u8,
    pub resend_seconds: u32,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SignupCodeProblem {
    WrongOrExpired,
    /// The guesses are spent or the server asks to slow down: a new code is the way on.
    TooManyWrong,
    Offline,
    Other,
    Left,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SignupPasswordProblem {
    Breached,
    /// The breach check could not be made and the server does not allow going on without it.
    CheckUnreachable,
    Other,
    Left,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SignupCreateProblem {
    /// Nothing was stored: trying again is safe.
    NothingStored,
    /// The account exists and this computer was not finished: the way on is to sign in, never to register again.
    NotFinishedHere,
    /// The email code ran out meanwhile: verify again; the password and the phrase are kept.
    CodeExpired,
    Left,
}

/// What a password being chosen is, by core's evaluator. Holds numbers, never a character of the password.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct SignupVerdict {
    /// 1 (too short) to 4 (strong).
    pub level: u8,
    pub meets_minimum: bool,
    pub min_length: u32,
    pub missing: u32,
    pub hint: SignupHint,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SignupHint {
    None,
    MoreCharacters,
    MixCaseAndNumberOrSymbol,
    MixCase,
    NumberOrSymbol,
}

/// One attempt to create an account. Cheap to make; owned by the host; see the module's doc.
pub struct SignupAttempt {
    /// The flow. Taken for one synchronous step at a time, never across a request.
    flow: Mutex<Option<SignupFlow>>,
    /// The server's numbers, copied out so the window's thread can evaluate a password without the flow's lock.
    policy: Mutex<Option<SignupPolicy>>,
    /// Which words are asked back, counted from zero: known once the phrase exists.
    positions: Mutex<Option<[usize; CONFIRM_WORDS]>>,
    /// The page the server named for signing up on the web.
    web: Mutex<Option<String>>,
    /// Bumped by every [`SignupAttempt::cancel`]: a call compares it with the value it started under.
    epoch: AtomicU64,
}

impl Default for SignupAttempt {
    fn default() -> Self {
        Self::new()
    }
}

fn locked<T>(mutex: &Mutex<T>) -> std::sync::MutexGuard<'_, T> {
    mutex.lock().unwrap_or_else(|poisoned| poisoned.into_inner())
}

impl SignupAttempt {
    pub fn new() -> Self {
        Self {
            flow: Mutex::new(None),
            policy: Mutex::new(None),
            positions: Mutex::new(None),
            web: Mutex::new(None),
            epoch: AtomicU64::new(0),
        }
    }

    fn epoch(&self) -> u64 {
        self.epoch.load(Ordering::SeqCst)
    }

    fn current(&self, epoch: u64) -> bool {
        self.epoch() == epoch
    }

    /// The person left: every call on its way ends with `Left` from this moment. Never waits (the flow may be
    /// held by a step that is running); [`SignupAttempt::cancel`] then wipes what the attempt held.
    pub fn leave(&self) {
        self.epoch.fetch_add(1, Ordering::SeqCst);
    }

    /// End the attempt: nothing of it is kept, and every call on its way ends with `Left`. Waits for a step that
    /// holds the flow, so a host calls it from its worker, after [`SignupAttempt::leave`] on its own thread.
    pub fn cancel(&self) {
        self.leave();
        if let Some(mut flow) = locked(&self.flow).take() {
            flow.wipe();
        }
        *locked(&self.policy) = None;
        *locked(&self.positions) = None;
        *locked(&self.web) = None;
    }

    /// The page the server named for signing up on the web, once it refused sign-up from this app. Only an `https`
    /// address on Beebeeb's own domain is ever kept.
    pub fn web_address(&self) -> Option<String> {
        locked(&self.web).clone()
    }

    /// How strong `password` is, by core's evaluator and the server's minimum. Local, at once, never waits.
    pub fn verdict(&self, password: &str) -> SignupVerdict {
        let policy = locked(&self.policy).clone().unwrap_or_default();
        let eval = beebeeb_core::signup_flow::evaluate(&policy, password);
        SignupVerdict {
            level: eval.strength.level(),
            meets_minimum: eval.meets_minimum,
            min_length: eval.min_length,
            missing: eval.missing_characters,
            hint: match eval.hint {
                PasswordHint::None => SignupHint::None,
                PasswordHint::NeedMoreCharacters => SignupHint::MoreCharacters,
                PasswordHint::MixCaseAndAddNumberOrSymbol => SignupHint::MixCaseAndNumberOrSymbol,
                PasswordHint::MixCase => SignupHint::MixCase,
                PasswordHint::AddNumberOrSymbol => SignupHint::NumberOrSymbol,
            },
        }
    }

    /// Which words are asked back, counted from zero. `None`: the phrase does not exist yet, or the server asks
    /// for a number of words the screens cannot draw.
    pub fn confirm_positions(&self) -> Option<[usize; CONFIRM_WORDS]> {
        *locked(&self.positions)
    }

    /// Lend the twelve words for one draw or one copy: `show` is called once while core holds them, and not at
    /// all when there is no phrase (not made yet, or already confirmed) or the worker is busy with the flow.
    /// Each word is a wiping buffer; none is kept.
    pub fn with_phrase(&self, show: &mut dyn FnMut(&[&str])) {
        // Only a phrase the worker made (it records the positions then): never one made here, on the window's thread.
        if locked(&self.positions).is_none() {
            return;
        }
        let Ok(mut guard) = self.flow.try_lock() else { return };
        let Some(flow) = guard.as_mut() else { return };
        let Ok(words) = flow.phrase_words() else { return };
        let borrowed: Vec<&str> = words.iter().map(|word| word.as_str()).collect();
        show(&borrowed);
    }

    fn with_flow<R>(&self, step: impl FnOnce(&mut SignupFlow) -> R) -> Option<R> {
        locked(&self.flow).as_mut().map(step)
    }

    fn policy(&self) -> Option<SignupPolicy> {
        locked(&self.policy).clone()
    }

    fn remember_web(&self, address: Option<String>) {
        *locked(&self.web) = address;
    }
}

/// The server's refusal of sign-up from this app: `403` with the code `signup_web_only`.
fn is_web_only(response: &beebeeb_core::auth_flow::HttpResponse) -> bool {
    response.status == 403 && body_code(&response.body) == Some("signup_web_only")
}

fn body_code(body: &serde_json::Value) -> Option<&str> {
    body.get("code")
        .and_then(|v| v.as_str())
        .or_else(|| body.get("error").and_then(|v| v.as_str()))
}

/// An `https` address on Beebeeb's own domain, plain host only (no credentials, no port, no backslash).
fn own_https_address(value: Option<&serde_json::Value>) -> Option<String> {
    let text = value?.as_str()?;
    if text.chars().any(|c| c.is_whitespace() || c.is_control() || c == '\\') {
        return None;
    }
    let rest = text.strip_prefix("https://")?;
    let end = rest.find(['/', '?', '#']).unwrap_or(rest.len());
    let host = rest[..end].to_ascii_lowercase();
    let plain = !host.is_empty()
        && host
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || b == b'-' || b == b'.');
    (plain && (host == "beebeeb.io" || host.ends_with(".beebeeb.io"))).then(|| text.to_owned())
}

/// The words of the public list that complete what is typed (at most `limit`), as static strings: what is typed is
/// never copied to make them. Nothing for an empty prefix.
pub fn word_suggestions(typed: &str, limit: usize) -> Vec<&'static str> {
    if typed.is_empty() {
        return Vec::new();
    }
    bip39::Language::English
        .words_by_prefix(typed)
        .iter()
        .take(limit)
        .copied()
        .collect()
}

fn seconds_of(retry_after: u64) -> u32 {
    u32::try_from(retry_after).unwrap_or(u32::MAX)
}

impl<C: CredentialStores> Engine<C> {
    /// Step 1 and the resend: send the email code (the first, and every new one: the old one stops working). The
    /// answer is the same for any address. `WebOnly`: the server does not take sign-ups from this app; nothing
    /// was sent, nothing is kept.
    pub fn signup_send_code(&self, attempt: &SignupAttempt, email: &str) -> Result<SignupCodeSent, SignupSendProblem> {
        self.runtime.block_on(async {
            let epoch = attempt.epoch();
            if self.auth_present.lock().map(|p| *p).unwrap_or(true) {
                // One account at a time: the person signs out first.
                return Err(SignupSendProblem::Other);
            }
            let policy = match attempt.policy() {
                Some(policy) => policy,
                None => {
                    let policy = self.signup_policy(attempt).await?;
                    if !attempt.current(epoch) {
                        return Err(SignupSendProblem::Left);
                    }
                    *locked(&attempt.policy) = Some(policy.clone());
                    policy
                }
            };
            let request = {
                let mut flow = locked(&attempt.flow);
                let flow = flow.get_or_insert_with(|| SignupFlow::new(policy.clone()));
                flow.send_code(email).map_err(|_| SignupSendProblem::Other)?
            };
            let response = auth_transport::send_to(&self.config.api_base, &self.client, None, request)
                .await
                .map_err(|_| SignupSendProblem::Offline)?;
            if !attempt.current(epoch) {
                return Err(SignupSendProblem::Left);
            }
            if is_web_only(&response) {
                attempt.remember_web(own_https_address(response.body.get("web_url")));
                return Err(SignupSendProblem::WebOnly);
            }
            let sent = attempt
                .with_flow(|flow| flow.on_code_sent(&response))
                .ok_or(SignupSendProblem::Left)?;
            match sent {
                Ok(()) => Ok(SignupCodeSent {
                    digits: u8::try_from(policy.code_length).unwrap_or(8),
                    resend_seconds: policy.resend_after_secs,
                }),
                Err(SignupError::RateLimited { retry_after_secs }) => Err(SignupSendProblem::RateLimited {
                    seconds: seconds_of(retry_after_secs),
                }),
                Err(_) => Err(SignupSendProblem::Other),
            }
        })
    }

    /// The server's numbers, and whether it takes a sign-up from this app at all (its onboarding document).
    async fn signup_policy(&self, attempt: &SignupAttempt) -> Result<SignupPolicy, SignupSendProblem> {
        let response = auth_transport::send_to(&self.config.api_base, &self.client, None, SignupPolicy::request())
            .await
            .map_err(|_| SignupSendProblem::Offline)?;
        if response.status == 429 {
            return Err(SignupSendProblem::RateLimited {
                seconds: seconds_of(response.retry_after_secs.unwrap_or(60)),
            });
        }
        let refused = is_web_only(&response)
            || response
                .body
                .get("signup")
                .is_some_and(|signup| signup.get("allowed").and_then(|v| v.as_bool()) == Some(false));
        if refused {
            let named = response
                .body
                .get("signup")
                .and_then(|signup| signup.get("web_url"))
                .or_else(|| response.body.get("web_url"));
            attempt.remember_web(own_https_address(named));
            return Err(SignupSendProblem::WebOnly);
        }
        SignupPolicy::from_response(&response).map_err(|_| SignupSendProblem::Other)
    }

    /// Step 2: check the code from the email. The ticket it earns stays in core's flow.
    pub fn signup_verify_code(&self, attempt: &SignupAttempt, code: &str) -> Result<(), SignupCodeProblem> {
        self.runtime.block_on(async {
            let epoch = attempt.epoch();
            let request = attempt
                .with_flow(|flow| flow.verify_code(code))
                .ok_or(SignupCodeProblem::Left)?
                .map_err(|_| SignupCodeProblem::WrongOrExpired)?;
            let response = auth_transport::send_to(&self.config.api_base, &self.client, None, request)
                .await
                .map_err(|_| SignupCodeProblem::Offline)?;
            if !attempt.current(epoch) {
                return Err(SignupCodeProblem::Left);
            }
            let verified = attempt
                .with_flow(|flow| flow.on_code_verified(&response))
                .ok_or(SignupCodeProblem::Left)?;
            match verified {
                Ok(()) => Ok(()),
                Err(SignupError::WrongCode) => Err(SignupCodeProblem::WrongOrExpired),
                Err(SignupError::RateLimited { .. }) => Err(SignupCodeProblem::TooManyWrong),
                Err(_) => Err(SignupCodeProblem::Other),
            }
        })
    }

    /// Step 4: the breach check, then core keeps the password for the account it will create, then core makes
    /// the recovery phrase (Argon2id, about a second: this is the slow step, so the screen shows its wait here
    /// and never while the words are drawn). Nobody goes on without the check's answer unless the server says the
    /// check may fail open (core applies that, not this module).
    pub fn signup_set_password(
        &self,
        attempt: &SignupAttempt,
        password: Zeroizing<String>,
    ) -> Result<(), SignupPasswordProblem> {
        self.runtime.block_on(async {
            let epoch = attempt.epoch();
            let request = attempt
                .with_flow(|flow| flow.breach_request(&password))
                .ok_or(SignupPasswordProblem::Left)?;
            if let Some(request) = request {
                let (status, text) = self.breach_answer(&request.path).await;
                if !attempt.current(epoch) {
                    return Err(SignupPasswordProblem::Left);
                }
                let _ = attempt.with_flow(|flow| flow.on_breach_response(status, &text));
            }
            let asked = attempt
                .with_flow(|flow| {
                    flow.set_password(&password, &password)?;
                    // Core makes the phrase now (idempotent); the words are wiped as they drop.
                    drop(flow.phrase_words()?);
                    flow.challenge_positions()
                })
                .ok_or(SignupPasswordProblem::Left)?;
            drop(password);
            let asked = asked.map_err(|error| match error {
                SignupError::PasswordBreached => SignupPasswordProblem::Breached,
                SignupError::BreachCheckBlocked | SignupError::BreachCheckMissing => {
                    SignupPasswordProblem::CheckUnreachable
                }
                _ => SignupPasswordProblem::Other,
            })?;
            if !attempt.current(epoch) {
                return Err(SignupPasswordProblem::Left);
            }
            // The screens ask for exactly three words (the board's rule and core's floor). A server that asks for
            // more is refused here, not drawn wrongly.
            let [a, b, c]: [u32; CONFIRM_WORDS] = asked.try_into().map_err(|_| SignupPasswordProblem::Other)?;
            let zero_based = |position: u32| (position as usize).saturating_sub(1);
            *locked(&attempt.positions) = Some([zero_based(a), zero_based(b), zero_based(c)]);
            Ok(())
        })
    }

    /// The range answer of the breach check, as text (core reads lines, not JSON). `None` status: no answer.
    async fn breach_answer(&self, path: &str) -> (Option<u16>, Zeroizing<String>) {
        let url = format!("{}{}", self.config.api_base, path);
        let Ok(response) = self.client.get(url).send().await else {
            return (None, Zeroizing::new(String::new()));
        };
        let status = response.status().as_u16();
        if response.content_length().is_some_and(|n| n as usize > BREACH_BODY_CAP) {
            return (None, Zeroizing::new(String::new()));
        }
        let text = response.text().await.unwrap_or_default();
        if text.len() > BREACH_BODY_CAP {
            return (None, Zeroizing::new(String::new()));
        }
        (Some(status), Zeroizing::new(text))
    }

    /// Step 5, second half: compare the typed-back words with the phrase, in core. The person ticked "I saved it"
    /// to reach this; core records that now. `true`: right. Says nothing of which word was wrong.
    pub fn signup_confirm_phrase(&self, attempt: &SignupAttempt, words: &[&str]) -> bool {
        let epoch = attempt.epoch();
        let right = attempt
            .with_flow(|flow| {
                flow.acknowledge_phrase()?;
                flow.confirm_phrase(words)
            })
            .is_some_and(|checked| checked.is_ok());
        if right && attempt.current(epoch) {
            *locked(&attempt.positions) = None;
        }
        right && attempt.current(epoch)
    }

    /// Step 6: register the account (OPAQUE, in core), then sign it in on this computer: the session token, the
    /// account's key and the email go to the credential store, the session goes into memory, the terms the person
    /// accepted are recorded. `device_name` names the computer on the screen only: no server route takes it.
    ///
    /// Before the server accepted the registration, every failure is `NothingStored` (or `CodeExpired`) and a retry
    /// is safe. After it, every failure is `NotFinishedHere`: the account exists, nothing is retried, and the
    /// session the server made is ended.
    pub fn signup_create(&self, attempt: &SignupAttempt, _device_name: &str) -> Result<(), SignupCreateProblem> {
        let result = self.runtime.block_on(self.signup_create_step(attempt));
        self.publish();
        result
    }

    async fn signup_create_step(&self, attempt: &SignupAttempt) -> Result<(), SignupCreateProblem> {
        use SignupCreateProblem::{CodeExpired, Left, NotFinishedHere, NothingStored};
        let _step = self.transition.lock().await;
        let epoch = attempt.epoch();
        let turn = self.acct.session_generation();
        if self.auth_present.lock().map(|p| *p).unwrap_or(true) {
            return Err(NothingStored);
        }
        let refusal = |error: SignupError| match error {
            SignupError::TicketExpired => CodeExpired,
            _ => NothingStored,
        };
        let start = attempt
            .with_flow(|flow| flow.register_start())
            .ok_or(Left)?
            .map_err(refusal)?;
        let answered = auth_transport::send_to(&self.config.api_base, &self.client, None, start)
            .await
            .map_err(|_| NothingStored)?;
        if !attempt.current(epoch) {
            return Err(Left);
        }
        let finish = attempt
            .with_flow(|flow| flow.on_register_start(&answered))
            .ok_or(Left)?
            .map_err(refusal)?;
        let answered = auth_transport::send_to(&self.config.api_base, &self.client, None, finish)
            .await
            .map_err(|_| NothingStored)?;
        // The registration is on its way to being accepted: from here the attempt being left does not stop it.
        let email = attempt.with_flow(|flow| flow.email().map(str::to_owned)).flatten();
        let accepted = answered.ok();
        let Some(finished) = attempt.with_flow(|flow| flow.on_register_finish(&answered)) else {
            // Left while the registration was being accepted: the account may exist, and nothing here holds its key.
            if let Some(token) = answered.body.get("session_token").and_then(|v| v.as_str()) {
                super::revoke(&self.client, &self.config.api_base, token).await;
            }
            return Err(if accepted { NotFinishedHere } else { NothingStored });
        };
        let created = finished.map_err(refusal)?;
        let terms = attempt.with_flow(|flow| flow.terms_request()).flatten();
        let token = created.session_token;
        let key = created.master_key.to_bytes();
        let email = email.unwrap_or_default();

        let installed = self.install_new_account(turn, &token, &key, &email).await;
        if installed.is_err() {
            // The account exists; this computer holds nothing of it. The session the server made is ended.
            super::revoke(&self.client, &self.config.api_base, &token).await;
            attempt.cancel();
            return Err(NotFinishedHere);
        }
        if let Some(request) = terms
            && auth_transport::send_to(&self.config.api_base, &self.client, Some(&token), request)
                .await
                .map(|answer| !answer.ok())
                .unwrap_or(true)
        {
            tracing::warn!("sign-up: the terms acceptance was not recorded");
        }
        // Done: nothing of the attempt is kept, and a late "leave" has nothing to wipe.
        if let Some(mut flow) = locked(&attempt.flow).take() {
            flow.wipe();
        }
        *locked(&attempt.positions) = None;
        Ok(())
    }

    /// Sign the account that was just made in on this computer: the order of `store_first_sign_in`, then the
    /// order of `unlock_with_phrase` for the key. A key that cannot be kept signs the session out again.
    async fn install_new_account(
        &self,
        turn: crate::account::SessionGeneration,
        token: &Zeroizing<String>,
        key: &Zeroizing<[u8; 32]>,
        typed_email: &str,
    ) -> Result<(), String> {
        let profile = super::fetch_profile(&self.client, &self.config.api_base, token).await?;
        let email = match profile.email.trim() {
            "" => typed_email.to_string(),
            named => named.to_string(),
        };
        self.store_first_sign_in(turn, token, &email, &profile)?;
        self.failures.store(0, Ordering::SeqCst);
        let turn = self.acct.session_generation();
        let kept = (|| -> Result<(), String> {
            let _write = self.claim(turn)?;
            let vault = self.vault();
            vault
                .store_wrapped_master_key(SecretBytes::new_master_key(key))
                .map_err(|e| store::keychain_error("store the account key", e))?;
            if let Err(error) = key_owner::bind_key_to_session_owner(&vault) {
                tracing::warn!(%error, "could not record the vault key's owner in the credential store");
            }
            let mut guard = self
                .acct
                .session
                .lock()
                .map_err(|_| "session mutex poisoned".to_string())?;
            *guard = Some(Session {
                token: token.to_string(),
                master_key: **key,
                email: Some(email),
            });
            drop(guard);
            self.acct
                .auth_resume_asked
                .fetch_add(1, std::sync::atomic::Ordering::SeqCst);
            Ok(())
        })();
        if kept.is_err() {
            // Signed in without its key is the half-way state sign-in's "twelve words" screen is for; a new account
            // has its phrase confirmed, but the key is lost to this computer, so end the session too.
            let _ = self.sign_out_holding_step().await;
        }
        kept
    }
}

